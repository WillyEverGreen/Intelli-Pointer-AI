// Generates src/renderer/icons.js from the Lucide icon set (ISC licence),
// keeping only the icons the UI uses. Re-run after adding a name below:
//   node scripts/build-icons.js
const fs = require('node:fs');
const path = require('node:path');

const NAMES = [
  'square-dashed', 'square', 'circle-dashed', 'lasso', 'pen-line', 'arrow-up-right', 'highlighter', 'eye-off',
  'undo-2', 'redo-2', 'trash-2', 'crop', 'pin', 'pin-off', 'chevron-down', 'chevron-up', 'settings', 'x', 'scan',
  'plus', 'refresh-cw', 'square-pen', 'globe', 'arrow-up', 'copy', 'check', 'rotate-ccw', 'lock', 'cloud',
  'message-square', 'image', 'type', 'corner-down-left', 'log-out', 'external-link', 'layers', 'list', 'keyboard',
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const version = require('lucide-static/package.json').version;
const icons = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  icons[name] = inner.replace(/\s*\n\s*/g, '').trim();
}

const out = `// Generated by scripts/build-icons.js — do not edit.
// Icons from Lucide v${version} (https://lucide.dev), ISC licence.
(() => {
  const ICONS = ${JSON.stringify(icons, null, 2)};

  // Returns an inline SVG string for a known icon name.
  window.ipIcon = (name, size = 16) => {
    const body = ICONS[name];
    if (!body) throw new Error(\`Unknown icon: \${name}\`);
    return \`<svg class="icon" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
  };

  // Fills every <… data-icon="name"> placeholder, keeping any existing text.
  window.ipApplyIcons = (root = document) => {
    for (const el of root.querySelectorAll('[data-icon]')) {
      if (el.querySelector(':scope > svg.icon')) continue;
      el.insertAdjacentHTML('afterbegin', window.ipIcon(el.dataset.icon, Number(el.dataset.iconSize) || 16));
    }
  };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'shared', 'icons.js'), out);
console.log(`icons.js: ${NAMES.length} icons from lucide-static ${version}`);
